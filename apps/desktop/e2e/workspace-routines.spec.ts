test("signing out before a scheduled occurrence gates unattended and manual dispatch", async ({ launchApp }) => {
  const { window, repoPath, home } = await launchApp({ configured: true, withRepo: true, piFixture: { scenarioId: "workspace-routines", authRoute: "api-key" } })
  await expect(appShell(window)).toBeVisible()
  await window.getByTestId("new-session").click(); await addProject(window, repoPath); await window.keyboard.press("Escape")
  await window.getByRole("button", { name: "Account menu" }).click()
  await window.getByRole("menuitem", { name: "Settings" }).click()
  await window.getByRole("button", { name: "Projects", exact: true }).click()
  const routines = window.getByRole("region", { name: "Saved desktop routines" })
  await routines.getByLabel("Name", { exact: true }).fill("Auth gated proof")
  await routines.getByLabel("Prompt", { exact: true }).fill("READONLY routine proof: inspect README.md")
  const dueAt = Date.now() + 10000
  const local = new Date(dueAt - new Date(dueAt).getTimezoneOffset() * 60000).toISOString().slice(0, 19)
  await routines.getByLabel("First occurrence").fill(local)
  await routines.getByRole("switch", { name: "Enable schedule" }).click()
  await routines.getByRole("checkbox", { name: /I approve these exact settings/ }).click()
  await routines.getByRole("button", { name: "Save routine", exact: true }).click()
  await expect(routines.getByRole("button", { name: "Disable Auth gated proof", exact: true })).toBeVisible()
  const document = () => JSON.parse(readFileSync(join(home, "jingler/routines.json"), "utf8"))
  const sessionIds = () => existsSync(join(home, "jingler/sessions.json")) ? JSON.parse(readFileSync(join(home, "jingler/sessions.json"), "utf8")).map((item: { id: string }) => item.id) : []
  const before = sessionIds()
  expect(document().runs).toEqual([])
  await window.getByRole("button", { name: "Close settings" }).click()
  await window.getByRole("button", { name: "Account menu" }).click()
  await window.getByRole("menuitem", { name: "Sign out", exact: true }).click()
  await expect(window.getByRole("button", { name: "Account menu" })).toContainText("Not signed in")
  // Prove signout completed before the occurrence rather than winning a timer race.
  expect(Date.now()).toBeLessThan(document().routines[0].nextAt)
  await expect.poll(() => {
    expect(document().runs).toEqual([])
    expect(sessionIds()).toEqual(before)
    return Date.now()
  }, { timeout: 15000, intervals: [250] }).toBeGreaterThan(dueAt + 1500)
  await window.getByRole("button", { name: "Account menu" }).click()
  await window.getByRole("menuitem", { name: "Settings" }).click()
  await window.getByRole("button", { name: "Projects", exact: true }).click()
  await routines.getByRole("button", { name: "Run now Auth gated proof", exact: true }).click()
  await expect(routines.getByRole("alert")).toContainText(/Sign in|signed out|suspended|unavailable/i)
  expect(document().runs).toEqual([])
  expect(sessionIds()).toEqual(before)
})
